"""Find the quotation PDFs, the tender BOQ and the site quantity sheet in the data pack, read them
(cached until a file changes) and turn the result into a deals seed for the vendor shortlist.

Pack folder: data/pack (git-ignored), override with QUOTES_PACK.
- 06_quotations/Quotation_*.pdf        one per vendor; the vendor name comes from the file name
- 03_tender/*BOQ*.pdf                  the BOQ sent to vendors, rates blank: the tender quantities
- 02_site_requirements/*quantit*.xlsx  the site quantity sheet: item codes, "not measured" lines
"""

from __future__ import annotations

import json
import os
import threading
from pathlib import Path

from ..intake.models import QuantitySheet
from ..intake.quantity_sheet import parse_quantity_sheet
from ..shortlist import deals as D
from . import compare as C
from . import parse as P
from .models import Comparison, Quote, TenderLine

ROOT = Path(__file__).resolve().parent.parent.parent
# Not "*quotes*.json": deals.seed_path() takes the first of those as the hand-made seed.
SEED_PATH = ROOT / "data" / "seed" / "parsed_quote_deals.json"
CATEGORY = "Waterproofing"

_lock = threading.Lock()
_cache: dict[tuple, object] = {}


def pack_dir() -> Path:
    return Path(os.environ.get("QUOTES_PACK") or ROOT / "data" / "pack")


def files() -> dict:
    p = pack_dir()
    quotes = sorted((p / "06_quotations").glob("Quotation_*.pdf")) if (p / "06_quotations").is_dir() else []
    tender = sorted((p / "03_tender").glob("*BOQ*.pdf")) if (p / "03_tender").is_dir() else []
    sheets = sorted((p / "02_site_requirements").glob("*quantit*.xlsx")) if (p / "02_site_requirements").is_dir() else []
    return {"quotes": quotes, "tender": tender[0] if tender else None, "sheet": sheets[0] if sheets else None}


def _key(paths: list[Path | None]) -> tuple:
    return tuple((str(x), x.stat().st_mtime_ns) for x in paths if x is not None and x.exists())


def _cached(key: tuple, fn):
    with _lock:
        if key not in _cache:
            _cache[key] = fn()
        return _cache[key]


def read_quotes() -> list[Quote]:
    qs = files()["quotes"]
    got = _cached(("quotes", *_key(qs)), lambda: [P.read_quote_safe(x) for x in qs])
    return [q.model_copy(deep=True) for q in got]  # compare() writes codes/basis onto them


def read_sheet() -> QuantitySheet | None:
    s = files()["sheet"]
    return _cached(("sheet", *_key([s])), lambda: parse_quantity_sheet(s.read_bytes(), s.name)) if s else None


def tender() -> list[TenderLine]:
    """The tender quantities: the BOQ sent to vendors, with item codes from the site sheet."""
    f = files()
    tender_lines = _cached(("tender", *_key([f["tender"]])), lambda: P.read_quote(f["tender"]).lines) if f["tender"] else None
    return [t.model_copy() for t in C.build_tender(tender_lines, read_sheet())]


def comparison() -> Comparison:
    return C.compare(tender(), read_quotes())


# ── Deals seed (the format procurement/shortlist/deals.py reads) ───────────────────────────────
def deals_seed(cmp: Comparison | None = None) -> dict:
    """Parsed rates in the shortlist's seed format. Scans that need vision are left out (no guessing)."""
    cmp = cmp or comparison()
    quotes = read_quotes()
    C.compare(cmp.tender, quotes)  # fills item codes on the lines
    sheet = read_sheet()
    out = []
    for q in quotes:
        if q.needs_vision:
            continue
        lead = q.term("lead_time_days")
        validity = q.term("validity_days")
        notes = [f"Read from the PDF text layer ({q.read_confidence} confidence)."]
        if q.quantity_basis == "different":
            notes.append("Priced on a different quantity set from the tender.")
        rates = []
        for ln in q.lines:
            if ln.rate is None or not ln.code:
                continue
            t = next((t for t in cmp.tender if t.sl_no == ln.sl_no), None)
            r = {"item_code": ln.code, "rate": ln.rate, "unit": ln.unit}
            if t is not None and t.unit != ln.unit:
                r["note"] = f"Quoted per {ln.unit_as_written} while the tender uses {t.unit.upper()}."
            rates.append(r)
        out.append({
            "vendor_name": q.vendor, "file": q.file, "date_quoted": q.date, "rfq_sent_at": None,
            "payment_terms": q.term("payment") or "", "gst": q.term("gst") or "",
            "validity_days": int(validity) if validity else None, "lead_time_days_promised": int(lead) if lead else None,
            "notes": " ".join(notes), "rates": rates,
        })
    lines = {t.code: t.description for t in cmp.tender if t.code}
    return {
        "about": "Generated by procurement/quotes from the quotation PDFs in the data pack. Real data: stays in data/ (git-ignored).",
        "project": _project_name(sheet),
        "category": CATEGORY,
        "lines": lines,
        "quotes": out,
    }


def _project_name(sheet: QuantitySheet | None) -> str:
    """Reuse the project name of a hand-made seed if there is one, so the same project isn't counted twice."""
    hand = D.seed_path()
    if hand is not None and hand.exists() and hand.resolve() != SEED_PATH.resolve():
        try:
            if name := json.loads(hand.read_text()).get("project"):
                return name
        except (ValueError, OSError):
            pass
    return sheet.title if sheet and sheet.title else ""


def write_seed(path: Path | None = None) -> Path:
    path = path or SEED_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(deals_seed(), indent=2, ensure_ascii=False) + "\n")
    return path


def sync_deals() -> dict:
    """Write the seed, then put the parsed rates in the deals store: for each quote file in the pack, the
    vendor's deals from that file are replaced. Deals from other files (e.g. a hand-read scan) stay."""
    path = write_seed()
    new = D.seed_deals(path)
    files_done = {x.name for x in files()["quotes"]} | {d.source.split(" · ")[0] for d in new}  # a file now a scan drops its old deals
    with D._lock:
        keep = [d for d in D.load_all() if d.source.split(" · ")[0] not in files_done]
        D.save_all(keep + new)
    return {"seed": str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path), "deals_written": len(new),
            "files": sorted(files_done), "kept": len(keep)}
